class TokenCounter:
    """Qwen3-VL text tokens. Exact with the real tokenizer.json (FL2VA/processor), else a
    calibrated estimate: 1.2 x word/punctuation pieces (the real ratio on this template is
    1.16, measured 2026-10-12)."""

    def __init__(self, path=None, required=False):
        self.tok, self.path = None, None
        cands = [path, os.environ.get("EXPV2_TOKENIZER"),
                 C.MODELS / C.H3_REPO / "FL2VA/processor/tokenizer.json"]
        for p in cands:
            if p and Path(p).is_file():
                try:
                    from tokenizers import Tokenizer
                    self.tok, self.path = Tokenizer.from_file(str(p)), str(p)
                    break
                except Exception as e:  # noqa: BLE001
                    log(f"  ! tokenizer at {p} unusable: {e}")
        if required and self.tok is None:
            sys.exit("--exact-tokens: no usable tokenizer.json (pass --tokenizer PATH or set "
                     "EXPV2_TOKENIZER; `pip install tokenizers`)")
        self.method = "exact" if self.tok else "estimate(1.2x pieces)"

    def __call__(self, text):
        if self.tok:
            return len(self.tok.encode(text, add_special_tokens=False).ids)
        return math.ceil(1.2 * len(re.findall(r"\w+|[^\w\s]", text)))


def assert_caption(cap, char, ntok):
    """§5.6 colour anchors (A10) and token budget."""
    low = cap.lower()
    if char == "Pax":
        assert "blue" in low and "pink" not in low, f"Pax caption colour anchors: {cap}"
    else:
        assert "pink" in low, f"Polly caption missing 'pink': {cap}"
    assert ntok <= C.MAX_CAPTION_TOKENS, f"{ntok} tokens > {C.MAX_CAPTION_TOKENS}: {cap}"


