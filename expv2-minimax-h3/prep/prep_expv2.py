def write_png_dir(frames, d):
    d.mkdir(parents=True, exist_ok=True)
    for i, f in enumerate(frames):
        Image.fromarray(f).save(d / f"{i:04d}.png", compress_level=PNG_LEVEL)


def write_mp4(frames, dest):
    """Lossless RGB H.264 with LOADER_TAIL copies of the last frame (MODEL_NOTES 2.17).
    libx264rgb at -qp 0 decodes back to rgb24 bit-exactly (check_loader.py verifies)."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    full = np.concatenate([frames] + [frames[-1:]] * C.LOADER_TAIL)
    p = subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24",
         "-s", f"{frames.shape[2]}x{frames.shape[1]}", "-r", str(FPS), "-i", "-",
         "-c:v", "libx264rgb", "-qp", "0", "-preset", "medium", "-pix_fmt", "rgb24",
         "-an", str(dest)], input=full.tobytes(), capture_output=True)
    if p.returncode:
        raise RuntimeError(f"ffmpeg failed on {dest}: {p.stderr.decode()[-400:]}")


def write_clip(root, cid, frames):
    write_mp4(frames, root / "clips" / f"{cid}.mp4")
    write_png_dir(frames, root / "png" / cid)


class Plan:
    """Everything the build writes, derived deterministically from preflighted jobs."""

    def __init__(self, jobs, toks):
        self.jobs = jobs
        self.toks = toks
        self.train, self.holdout, self.calib, self.bank, self.starts = [], [], [], [], []
        self.vae, self.max_tokens = [], 0
        for j in jobs:
            if j["split"] == "train":
                for n in j["rungs"]:
                    for g in C.TRAINED_GROUNDS:
                        self.train.append(self._clip(j, "train", g, j["zooms"][g], n))
                if j["base_angle"] == C.CALIB_ANGLE:
                    self.calib.append(self._clip(j, "calib", "white", 1.00, C.FLOOR))
            elif j["split"] == "holdout":
                self.holdout.append(self._clip(j, "holdout", "white", 1.00, C.FLOOR))
            if j.get("bank_frames"):
                n = j["bank_frames"]
                m, how = frame_map(j, n) if j["split"] != "untrained" else (list(range(n)), "none")
                self.bank.append({"bank_id": f"{j['char'].lower()}_{j['label']}_{j['angle']}",
                                  "char": j["char"], "label": j["label"], "kind": j["kind"],
                                  "angle": j["angle"], "frames": n,
                                  "split": j["split"], "source": rel(j["src"]), "md5": j["md5"],
                                  "usable_frames": j["usable"], "held_frame": how == "held",
                                  "tiled": how == "tiled", "_job": j, "_map": m})
            if j["base_angle"] in ("FRONT", C.HOLDOUT_ANGLE) and j.get("start_ok", True) \
                    and j["usable"] >= 1:
                for g in ("white", "lavender", "skyblue"):
                    self.starts.append({"char": j["char"], "label": j["label"],
                                        "angle": j["angle"], "ground": g,
                                        "path": f"start_frames/{j['char'].lower()}_{j['label']}_"
                                                f"{j['angle']}__{g}.png",
                                        "source": rel(j["src"]), "_job": j})
            if j["base_angle"] == "FRONT" and j["label"] in ("angry", "waving", "walking") \
                    and j["usable_f22"]:
                n = 39 if j["label"] == "angry" else C.FLOOR
                m, how = frame_map(j, n)
                if m is not None:
                    for g in ("white", "mint"):
                        self.vae.append({"id": f"{j['char'].lower()}_{j['label']}_FRONT__{g}_f{n}",
                                         "char": j["char"], "label": j["label"], "ground": g,
                                         "frames": n, "tiled": how == "tiled",
                                         "source": rel(j["src"]), "_job": j, "_map": m})

    def _clip(self, j, split, ground, zoom, n):
        m, how = frame_map(j, n)
        assert m is not None, (j["src"], n)
        check_map(j, n, m, how)
        tr = truncated(j, n)
        cap = C.caption(j["char"], j["label"], j["base_angle"], ground, zoom, tr)
        ntok = self.toks(cap)
        assert_caption(cap, j["char"], ntok)
        self.max_tokens = max(self.max_tokens, ntok)
        cid = C.clip_id(j["char"], j["label"], j["angle"], ground, zoom, n)
        sub = {"train": "", "holdout": "holdout/", "calib": "calib/"}[split]
        return {"clip_id": cid, "split": split, "char": j["char"], "label": j["label"],
                "kind": j["kind"], "angle": j["angle"], "ground": ground, "zoom": zoom,
                "frames": n, "source": rel(j["src"]), "source_md5": j["md5"],
                "usable_frames": j["usable"], "held_frame": how == "held",
                "tiled": how == "tiled", "truncated": tr, "caption": cap, "tokens": ntok,
                "mp4": f"{sub}clips/{cid}.mp4", "png_dir": f"{sub}png/{cid}",
                "_job": j, "_map": m}

    def by_source(self):
        d = collections.defaultdict(lambda: collections.defaultdict(list))
        for part, items in (("train", self.train), ("holdout", self.holdout),
                            ("calib", self.calib), ("bank", self.bank),
                            ("start_frames", self.starts), ("vae_gate", self.vae)):
            for it in items:
                d[id(it["_job"])][part].append(it)
        return d


def build_source(job, parts, out, items_by_part):
    """Decode one source at every zoom it needs, then write every output it owes.
    Decodes everything first so a damaged source leaves nothing half-written."""
    need = 1
    zooms = set()
    for part, items in items_by_part.items():
        if part not in parts:
            continue
        for it in items:
            if part == "start_frames":
                # decode a few frames so the tear check has a median to compare against
                zooms.add(1.00)
                need = max(need, min(job["usable"], 8))
                continue
            if part == "vae_gate":
                need = max(need, max(it["_map"]) + 1)
                continue
            need = max(need, max(it["_map"]) + 1)
            zooms.add(it.get("zoom", 1.00) if part in ("train", "holdout", "calib") else 1.00)
    vae_items = items_by_part.get("vae_gate", []) if "vae_gate" in parts else []
    if vae_items:
        zooms.add(1.00)
    need = min(need, job["usable"]) if job["usable"] >= 1 else need
    decoded, written = {}, []
    try:
        for z in sorted(zooms):
            decoded[(z, SIZE)] = decode_checked(job["src"], need, z, SIZE)
        if vae_items:
            decoded[(1.00, 512)] = decode_checked(job["src"], need, 1.00, 512)
    except (RuntimeError, subprocess.CalledProcessError) as e:
        return {"error": str(e).strip()[-300:]}

    for part in ("train", "holdout", "calib"):
        if part not in parts:
            continue
        root = out if part == "train" else out / part
        for it in items_by_part.get(part, []):
            rgba = decoded[(it["zoom"], SIZE)][it["_map"]]
            frames = composite(rgba, C.GROUNDS[it["ground"]][1])
            write_clip(root, it["clip_id"], frames)
            written.append(it["clip_id"])
    if "bank" in parts:
        for it in items_by_part.get("bank", []):
            rgba = decoded[(1.00, SIZE)][it["_map"]]
            write_png_dir(composite(rgba, C.GROUNDS["white"][1]), out / "bank/png" / it["bank_id"])
    if "start_frames" in parts:
        for it in items_by_part.get("start_frames", []):
            f0 = composite(decoded[(1.00, SIZE)][:1], C.GROUNDS[it["ground"]][1])[0]
            p = out / it["path"]
            p.parent.mkdir(parents=True, exist_ok=True)
            Image.fromarray(f0).save(p, compress_level=PNG_LEVEL)
    for it in vae_items:
        for size in (768, 512):
            rgba = decoded[(1.00, size)][it["_map"]]
            write_png_dir(composite(rgba, C.GROUNDS[it["ground"]][1]),
                          out / f"vae_gate/png{size}" / it["id"])
    return {"error": None, "written": written}


