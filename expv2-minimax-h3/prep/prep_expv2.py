ACTIVE_EPS = 0.5              # copied from ltx25/prep/prep_ltx25.py ACTIVE_EPS
HUE_PAX_MIN = 0.5             # >= half the saturated character pixels blue -> Pax
HUE_POLLY_MAX = 0.05          # <= 5% blue -> Polly; in between -> disagreement


def real_frame_gap(path):
    """Copied from finetune/wan/prep_v8.py real_frame_gap at b902bde.

    Index of the first frame the stream does NOT actually contain, or None. ffmpeg's
    constant-rate output silently fills each gap with a duplicate of the previous frame,
    so a decode "succeeds" and a tear check passes; the timestamps are the ground truth."""
    out = subprocess.run(
        ["ffprobe", "-v", "quiet", "-select_streams", "v:0", "-show_entries",
         "frame=pts_time", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True).stdout.split()
    idx = sorted({int(round(float(t) * FPS)) for t in out if t.strip() and t.strip() != "N/A"})
    for i, k in enumerate(idx):
        if k != i:
            return i
    return None


def active_frames(path, total):
    """Copied from ltx25/prep/prep_ltx25.py active_frames at b902bde (timeout dropped).

    Frames up to and including the last one that actually moves (mean abs 8-bit
    difference >= 0.5 on a 128 px grey decode). Frozen holds inside a clip are kept;
    only the dead tail is measured away (A5)."""
    out = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path),
         "-vf", "scale=128:128,format=gray", "-frames:v", str(total), "-f", "rawvideo", "-"],
        capture_output=True).stdout
    n = 128 * 128
    c = len(out) // n
    if c < 2:
        return total
    g = np.frombuffer(out[:c * n], dtype=np.uint8).reshape(c, 128, 128).astype(np.float32)
    d = np.abs(np.diff(g, axis=0)).mean(axis=(1, 2))
    moving = np.where(d >= ACTIVE_EPS)[0]
    if len(moving) == 0:
        return 1
    return min(total, int(moving[-1]) + 2)


def find_torn(alpha, n):
    """Copied from finetune/wan/prep_v8.py find_torn at b902bde.

    Indices of torn frames within the first n: a frame under 0.6x the clip's median alpha
    coverage is decoder damage, not animation."""
    cover = (alpha > 8).reshape(len(alpha), -1).mean(1)
    med = float(np.median(cover))
    if med <= 0:
        return list(range(min(n, len(cover))))
    return [int(i) for i in np.where(cover[:n] < TORN_FRAC * med)[0]]


def read_rgba(path, nframes, size=SIZE):
    """Copied from finetune/wan/prep_v8.py read_rgba at b902bde.
    Decode ProRes 4444 -> (nframes, size, size, 4) uint8, alpha preserved."""
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-vf", f"scale={size}:{size}",
         "-frames:v", str(nframes), "-pix_fmt", "rgba", "-f", "rawvideo", "-"],
        capture_output=True, check=True).stdout
    arr = np.frombuffer(raw, np.uint8).reshape(-1, size, size, 4)
    if arr.shape[0] < nframes:
        raise RuntimeError(f"{Path(path).name}: got {arr.shape[0]} frames, need {nframes}")
    return arr[:nframes]


def read_rgba_zoomed(path, nframes, zoom, size=SIZE):
    """Copied from finetune/wan/prep_v8.py read_rgba_zoomed at b902bde (size param added).

    One resample straight from the 1080 source to round(size*zoom), centred on a
    transparent canvas; the flat ground shows through the padding after compositing, so
    it is regenerated rather than resampled (no halos)."""
    if zoom >= 0.999:
        return read_rgba(path, nframes, size)
    n = int(round(size * zoom))
    n -= n % 2
    small = read_rgba(path, nframes, size=n)
    canvas = np.zeros((nframes, size, size, 4), np.uint8)
    off = (size - n) // 2
    canvas[:, off:off + n, off:off + n] = small
    return canvas


def decode_checked(path, need, zoom, size=SIZE):
    """Copied from finetune/wan/prep_v8.py decode_checked at b902bde (path/size params).

    Decode, then verify no torn frame reached the array; retry because the damage is
    non-deterministic. Never "repaired" by cutting frames out (a jump cut)."""
    last = None
    for _ in range(DECODE_TRIES):
        frames = read_rgba_zoomed(path, need, zoom, size)
        torn = find_torn(frames[..., 3], need)
        if not torn:
            return frames
        last = torn
    raise RuntimeError(f"torn frames {last} within the first {need} at zoom {zoom:.2f} "
                       f"size {size} after {DECODE_TRIES} decodes - corrupt ProRes")


def composite(frames, rgb):
    """Copied from finetune/wan/prep_v8.py composite at b902bde."""
    a = frames[..., 3:4].astype(np.float32) / 255.0
    fg = frames[..., :3].astype(np.float32)
    return (fg * a + np.array(rgb, np.float32) * (1 - a)).round().astype(np.uint8)


def body_hue(rgba):
    """Share of saturated character pixels that are blue (Pax's body). Polly is pastel
    pink, so few of her pixels pass the saturation bar and none of them are blue."""
    a = rgba.astype(np.float32) / 255.0
    m = a[..., 3] > 0.8
    rgb = a[..., :3][m]
    if len(rgb) == 0:
        return 0.0
    mx, mn = rgb.max(1), rgb.min(1)
    d = np.maximum(mx - mn, 1e-6)
    s = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-6), 0)
    r, g, b = rgb.T
    h = np.where(mx == r, ((g - b) / d) % 6, np.where(mx == g, (b - r) / d + 2, (r - g) / d + 4)) * 60
    sel = (s > 0.25) & (mx > 0.35)
    if not sel.any():
        return 0.0
    hh = h[sel]
    return float(((hh >= 180) & (hh <= 260)).mean())


def preflight(job):
    """Structural measurements on one source; no output written.

    usable = frames before the first missing timestamp (or every decoded frame);
    active = frames up to the last moving one (A5); walking: loop seam (A11);
    hue = body-colour share (A9: the character must match its name)."""
    src = job["src"]
    job["first_gap"] = real_frame_gap(src)
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(src), "-vf", f"scale={PREFLIGHT_SIZE}:{PREFLIGHT_SIZE}",
         "-pix_fmt", "rgba", "-f", "rawvideo", "-"], capture_output=True).stdout
    v = np.frombuffer(raw, np.uint8).reshape(-1, PREFLIGHT_SIZE, PREFLIGHT_SIZE, 4)
    job["src_frames"] = int(len(v))
    usable = len(v) if job["first_gap"] is None else min(len(v), job["first_gap"])
    job["usable"] = int(usable)
    job["active"] = int(active_frames(src, usable)) if usable >= 2 else int(usable)
    job["hue_blue"] = round(body_hue(v[0]), 3) if len(v) else None
    job["seam_ratio"] = None
    if job["label"] == "walking" and usable > 2:
        # Copied from prep_v8.preflight's loop-seam measure: masked RGB MAE (0-255)
        # between first and last USABLE frame / median frame step.
        f = v[:usable].astype(np.float32)

        def mae(a, b):
            m = (a[..., 3] > 8) | (b[..., 3] > 8)
            return float(np.abs(a[..., :3] - b[..., :3])[m].mean()) if m.any() else 0.0
        step = float(np.median([mae(f[i], f[i + 1]) for i in range(len(f) - 1)]))
        job["seam_ratio"] = round(mae(f[-1], f[0]) / step, 3) if step > 0 else 99.0
    return job


