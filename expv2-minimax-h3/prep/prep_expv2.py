PREFLIGHT_SIZE = 192          # copied from prep_v8: cheap decode, structural check only
TORN_FRAC = 0.6               # copied from prep_v8 find_torn
DECODE_TRIES = 24             # copied from prep_v8 (A7: 0.5^24 = 6e-8 spurious-drop rate)
LOOP_SEAM_MAX = 1.5           # copied from prep_v8: seam / median step
