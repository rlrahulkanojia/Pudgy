def parse_angle(stem):
    """Copied from finetune/wan/prep_v8.py parse_angle at b902bde (clause dropped: the
    caption clause comes from C.angle_clause(slug)).

    Five angle vocabularies: FRONT/FR, SIDE_L/Right, QF_L, QF1_L, QF_L2. Bare QF names are
    marked QF?_<side> and re-indexed by resolve_bare_quarters()."""
    toks = [t for t in re.split(r"[_\-]", stem.upper()) if t and t not in NOISE]
    if not toks:
        return None
    if toks[0] in ("FRONT", "FR"):
        return "FRONT"
    if toks[0] == "SIDE" and len(toks) > 1 and toks[1][0] in "LR":
        return f"SIDE_{toks[1][0]}"
    if toks[0] in ("RIGHT", "LEFT"):                    # v5's odd "Right.mov"
        return f"SIDE_{toks[0][0]}"
    if toks[0].startswith("QF"):
        joined = "".join(toks)
        m = re.search(r"([LR])", joined)
        if not m:
            return None
        d = m.group(1)
        digits = re.findall(r"\d", joined)
        # EXPLICIT QF1_R / QF2_R / QF3_R: the digit before the side letter IS the angle.
        # BARE QF_R / QF_R1 / QF_L2: the suffix is an offset in some folders and an index
        # in others (verified against the footage in v8), so bare names are re-indexed by
        # sorted order.
        if re.match(r"QF\d", toks[0]):
            return f"QF{min(max(int(digits[0]), 1), 3)}_{d}"
        return f"QF?_{d}"
    return None


def resolve_bare_quarters(jobs):
    """Copied from finetune/wan/prep_v8.py resolve_bare_quarters at b902bde.

    Assign a degree to bare `QF_<side>[n]` names from their order within the group:
    explicit names keep their stated degree, bare ones take the lowest free degrees in
    sorted filename order."""
    groups = collections.defaultdict(list)
    taken = collections.defaultdict(set)
    for j in jobs:
        if not j["angle"].startswith("QF"):
            continue
        key = (j["char"], j["label"], j["angle"][-1])
        if j["angle"].startswith("QF?"):
            groups[key].append(j)
        else:
            taken[key].add(int(j["angle"][2]))
    fixed = []
    for key, g in sorted(groups.items()):
        g.sort(key=lambda x: x["src"].name)
        free = [d for d in (1, 2, 3) if d not in taken[key]]
        if len(g) > len(free):
            sys.exit(f"{key}: {len(g)} bare quarter files but only {len(free)} free degrees")
        for j, deg in zip(g, free):
            fixed.append((rel(j["src"]), f"QF{deg}_{key[2]}"))
            j["angle"] = f"QF{deg}_{key[2]}"
    return fixed


def md5(path):
    """Copied from finetune/wan/prep_v8.py md5 at b902bde."""
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def discover():
    """Every single-character source we know how to caption, md5-deduplicated.

    Adapted from finetune/wan/prep_v8.py discover at b902bde: same trees, same order
    (iteration_3 expressions first, so canonical names win over re-drops), same handling
    of the mixed-case HAPPY/Pax folder and the misfiled HAPPY/POLLY/PAX_* file (the
    filename wins; the measured body hue must then agree, see preflight). What changed:
    the label vocabulary is expv2's (no standing_idle), and a filename that names a
    different label than its folder must have a recorded call in
    RESOLVED_LABEL_DISAGREEMENTS, or discovery exits (A9).

    Returns (jobs, excluded, rebased, collisions). `excluded` lists every .mov under
    iteration_3..5 that is not a job, with its reason: nothing is dropped silently.
    """
    jobs, excluded, unresolved = [], [], []
    seen = {}
    consumed = set()

    def add(src, char, label, kind):
        consumed.add(src.resolve())
        slug = parse_angle(src.stem)
        if not slug:
            excluded.append({"source": rel(src), "md5": md5(src), "reason": "unparseable angle"})
            return
        h = md5(src)
        if h in seen:
            excluded.append({"source": rel(src), "md5": h,
                             "reason": f"md5 duplicate of {rel(seen[h])}"})
            return
        seen[h] = src
        jobs.append({"src": src, "md5": h, "char": char, "label": label, "kind": kind,
                     "angle": slug, "named_char": char})

    def exclude(src, reason):
        consumed.add(src.resolve())
        h = md5(src)
        if h in seen:
            reason = f"{reason}; also md5 duplicate of {rel(seen[h])}"
        else:
            seen[h] = src
        excluded.append({"source": rel(src), "md5": h, "reason": reason})

    chars = {"PAX": "Pax", "POLLY": "Polly"}

    # --- iteration_3 expressions (canonical names) -----------------------------------
    if SRC_IT3.exists():
        for char_dir in sorted(p for p in SRC_IT3.iterdir() if p.is_dir()):
            char = chars.get(char_dir.name.upper())
            for emo_dir in sorted(p for p in char_dir.iterdir() if p.is_dir()):
                for c in sorted(emo_dir.glob("*.mov")):
                    if not char:
                        exclude(c, "unknown character folder")
                    elif emo_dir.name not in C.EXPRESSIONS:
                        exclude(c, f"no caption recipe for '{emo_dir.name}' (not delivered "
                                   f"as a trained label)")
                    else:
                        add(c, char, emo_dir.name, "expression")

    # --- iteration_4 / iteration_5 ------------------------------------------------------
    for it_root in (SRC_IT4, SRC_IT5):
        expr = it_root / "EXPRESSIONS"
        if expr.exists():
            for lab_dir in sorted(p for p in expr.iterdir() if p.is_dir()):
                key = {"SURPRISE": "surprised"}.get(lab_dir.name, lab_dir.name.lower())
                char_dirs = [p for p in lab_dir.iterdir() if p.is_dir()]
                if not char_dirs:                     # e.g. TURNAROUND (a single file)
                    for c in sorted(lab_dir.glob("*.mov")):
                        exclude(c, "identity reference (turnaround), not a performance")
                    continue
                for cd in sorted(char_dirs):
                    char = chars.get(cd.name.upper())
                    for c in sorted(cd.glob("*.mov")):
                        if key not in C.EXPRESSIONS:
                            exclude(c, f"no caption recipe for '{lab_dir.name}'"); continue
                        if not char:
                            exclude(c, "unknown character folder"); continue
                        # A file whose NAME says a different character than its folder is
                        # misfiled (HAPPY/POLLY/PAX_HAPPY_SIDE_R.mov). Trust the name; the
                        # body-hue check in preflight must agree.
                        named = next((v for k, v in chars.items()
                                      if c.stem.upper().startswith(k)), None)
                        add(c, named or char, key, "expression")

        motion = it_root / "MOTION_CLIPS"
        if motion.exists():
            for act_dir in sorted(p for p in motion.iterdir() if p.is_dir()):
                key = act_dir.name.upper().replace("MOTION_", "").lower()
                for cd in sorted(p for p in act_dir.iterdir() if p.is_dir()):
                    char = chars.get(cd.name.upper())
                    for c in sorted(cd.glob("*.mov")):
                        if key not in C.MOTION:
                            exclude(c, f"no caption recipe for '{act_dir.name}'"); continue
                        if not char:
                            exclude(c, "unknown character folder"); continue
                        other = [a for a in C.MOTION if a != key and a.upper() in c.stem.upper()]
                        if other:
                            call = RESOLVED_LABEL_DISAGREEMENTS.get((key, other[0]))
                            if call is None:
                                unresolved.append(f"{rel(c)}: folder says {key}, filename "
                                                  f"says {other[0]}")
                                consumed.add(c.resolve())
                            else:
                                exclude(c, call)
                            continue
                        add(c, char, key, "motion")

        inter = it_root / "INTERACTION_CLIPS"
        if inter.exists():
            for c in sorted(inter.rglob("*.mov")):
                exclude(c, "two-character clip, out of scope (A14)")

    if unresolved:
        for u in unresolved:
            log(f"  !! unresolved naming disagreement: {u}")
        sys.exit("refusing to run: naming disagreements without a recorded call (A9). Add a "
                 "decision to RESOLVED_LABEL_DISAGREEMENTS.")

    # Anything else under iteration_3..5 (turnaround, character sheets, ...): listed.
    for it in ("iteration_3", "iteration_4", "iteration_5"):
        for c in sorted((C.RAW / it).rglob("*")):
            if c.suffix.lower() == ".mov" and c.resolve() not in consumed:
                exclude(c, "outside the single-character expression/motion trees "
                           "(character design or reference material)")

    rebased = resolve_bare_quarters(jobs)

    # Two takes can parse to the same angle: keep both, under _t1/_t2 (copied from
    # prep_v8.discover). The holdout and caption use the base angle.
    collisions, groups = [], collections.defaultdict(list)
    for j in jobs:
        groups[(j["char"], j["label"], j["angle"])].append(j)
    for (char, lab, slug), g in groups.items():
        if len(g) > 1:
            g.sort(key=lambda x: x["src"].name)
            for i, j in enumerate(g, 1):
                j["angle"] = f"{slug}_t{i}"
            collisions.append((f"{char}/{lab}/{slug}", [rel(x["src"]) for x in g]))
    for j in jobs:
        j["base_angle"] = j["angle"].split("_t")[0]
    return jobs, excluded, rebased, collisions


