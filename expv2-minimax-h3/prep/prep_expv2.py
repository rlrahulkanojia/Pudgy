def eval_items(plan, toks):
    """Every generation item of every suite (INTERFACES §1, PLAN §7.4)."""
    starts = {(s["char"], s["label"], s["angle"].split("_t")[0], s["ground"]): s
              for s in plan.starts}
    specs = []
    for lab in C.ALL_LABELS:
        for ch in C.CHARS:
            for ang in ("FRONT", C.HOLDOUT_ANGLE):
                specs.append(("core", ch, lab, ang, "white", C.FLOOR, list(C.SEEDS)))
    for lab, n in (("angry", 39), ("laughing", 39), ("blushing", 39), ("neutral", 56)):
        for ch in C.CHARS:
            specs.append(("native", ch, lab, C.HOLDOUT_ANGLE, "white", n, list(C.SEEDS)))
    for lab in ("angry", "waving", "jumping"):
        for ch in C.CHARS:
            for g in ("lavender", "skyblue"):
                specs.append(("gb", ch, lab, C.HOLDOUT_ANGLE, g, C.FLOOR, list(C.SEEDS)))
    for lab in C.MOTION_TRAINED:
        for ch in C.CHARS:
            specs.append(("probe", ch, lab, C.HOLDOUT_ANGLE, "white", C.FLOOR, [C.PROBE_SEED]))
    # v8's rule (finetune/wan/eval_v8/build_assets_v8.py): every generation item, whatever
    # its label, starts from frame 0 of that character's NEUTRAL source at the item's angle
    # and ground. The start frame then carries no label signal - the label lives in the
    # prompt only, which V4 (controllability) needs and which keeps §8 comparable with
    # v8@550. The per-label start_frames/ files are still written, for analysis.
    # `truncated` stays computed against the LABEL's own source at that angle: it is the
    # training-caption rule, and the caption must match what the label was trained with.
    label_src = {(j["char"], j["label"], j["base_angle"]): j for j in plan.jobs}
    items, missing = [], []
    for suite, ch, lab, ang, g, n, seeds in specs:
        s = starts.get((ch, START_SOURCE_LABEL, ang, g))
        iid = f"{suite}__{ch.lower()}_{lab}_{ang}__{g}_f{n}"
        if s is None:
            missing.append(f"{iid}: no {START_SOURCE_LABEL} start frame for {ch} {ang} {g}")
            continue
        j = label_src.get((ch, lab, ang))
        if j is None and lab != "running":
            missing.append(f"{iid}: no {lab} source for {ch} at {ang} to set `truncated`")
            continue
        tr = lab != "running" and truncated(j, n)
        cap = C.caption(ch, lab, ang, g, 1.00, tr)
        assert_caption(cap, ch, toks(cap))
        items.append({"item_id": iid, "suite": suite, "char": ch, "label": lab,
                      "kind": C.kind_of(lab), "angle": ang, "ground": g, "frames": n,
                      "seeds": seeds, "start_frame": s["path"],
                      "start_source_label": START_SOURCE_LABEL, "caption": cap,
                      "truncated": tr})
    return items, missing


