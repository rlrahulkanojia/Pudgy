# Post-build verification (§5.6)
# ---------------------------------------------------------------------------------------
def verify_outputs(out, plan, workers):
    problems = []
    clip_items = plan.train + plan.holdout + plan.calib

    def one(it):
        mp4 = out / it["mp4"]
        r = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-count_packets",
                            "-show_entries", "stream=nb_read_packets,width,height,pix_fmt",
                            "-of", "json", str(mp4)], capture_output=True, text=True)
        st = (json.loads(r.stdout or "{}").get("streams") or [{}])[0]
        n = it["frames"]
        errs = []
        if n % 17 != 5:
            errs.append(f"{it['clip_id']}: {n} not on the 17n+5 grid")
        if int(st.get("nb_read_packets", -1)) != n + C.LOADER_TAIL:
            errs.append(f"{it['clip_id']}: mp4 has {st.get('nb_read_packets')} frames, want "
                        f"{n + C.LOADER_TAIL}")
        if (st.get("width"), st.get("height")) != (SIZE, SIZE):
            errs.append(f"{it['clip_id']}: mp4 {st.get('width')}x{st.get('height')}")
        pngs = sorted((out / it["png_dir"]).glob("*.png"))
        if len(pngs) != n:
            errs.append(f"{it['clip_id']}: {len(pngs)} PNGs, want {n}")
        return errs, md5(mp4)

    with ThreadPoolExecutor(workers) as ex:
        res = list(ex.map(one, clip_items))
    by_hash = collections.defaultdict(list)
    for it, (errs, h) in zip(clip_items, res):
        problems += errs
        by_hash[h].append(it)
    # The only legitimate byte-identical pair: a calib clip and the training clip with the
    # SAME id (its source drew zoom 1.00 on white, so calib re-renders exactly that clip).
    for h, its in by_hash.items():
        if len(its) < 2:
            continue
        ok = (len(its) == 2 and {i["split"] for i in its} == {"train", "calib"}
              and its[0]["clip_id"] == its[1]["clip_id"])
        if not ok:
            problems.append("byte-identical clips: " + ", ".join(f"{i['split']}/{i['clip_id']}"
                                                                 for i in its))
    for b in plan.bank:
        k = len(list((out / "bank/png" / b["bank_id"]).glob("*.png")))
        if k != b["frames"]:
            problems.append(f"bank {b['bank_id']}: {k} PNGs, want {b['frames']}")
    for s in plan.starts:
        if not (out / s["path"]).is_file():
            problems.append(f"missing start frame {s['path']}")
    # holdout disjointness, by md5 and by (char, label, angle)
    tr_md5 = {c["source_md5"] for c in plan.train}
    tr_key = {(c["char"], c["label"], c["angle"].split("_t")[0]) for c in plan.train}
    for h in plan.holdout:
        if h["source_md5"] in tr_md5 or (h["char"], h["label"], h["angle"].split("_t")[0]) in tr_key:
            problems.append(f"holdout {h['clip_id']} leaks into training")
    return problems


# ---------------------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--out", type=Path, default=C.CORPUS)
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--dry-run", action="store_true", help="plan + §5.2 table; writes nothing")
    ap.add_argument("--only", nargs="+", metavar="PART",
                    choices=("train", "holdout", "calib", "bank", "start_frames", "vae_gate", "json"),
                    help="rebuild only these parts IN PLACE in an existing corpus (JSON/CSV "
                         "are always rewritten)")
    ap.add_argument("--force", action="store_true", help="replace an existing corpus")
    ap.add_argument("--exact-tokens", action="store_true",
                    help="require the real Qwen3-VL tokenizer for the 220-token assertion")
    ap.add_argument("--tokenizer", type=Path, default=None, help="path to tokenizer.json")
    ap.add_argument("--accept-counts", action="store_true",
                    help="build even if the per-label counts disagree with PLAN §5.2; the "
                         "deviations are recorded in manifest.json (count_deviations)")
    args = ap.parse_args()
    t0 = time.time()

    toks = TokenCounter(args.tokenizer, required=args.exact_tokens)
    log(f"raw: {C.RAW}   out: {args.out}   tokens: {toks.method}")
    jobs, excluded, rebased, collisions = discover()
    log(f"discovered {len(jobs)} unique sources; {len(excluded)} files excluded or duplicate")
    for before, after in rebased:
        log(f"  ° re-indexed {before} -> {after}")
    for slug, srcs in collisions:
        log(f"  ~ disambiguated {slug}: {srcs}")

    log(f"preflight: timestamps, decode, active length, seam, hue on {len(jobs)} sources ...")
    with ThreadPoolExecutor(args.workers) as ex:
        jobs = list(ex.map(preflight, jobs))

    # A9/A10: the measured body colour must agree with the character the name gives.
    bad = []
    for j in jobs:
        hb = j["hue_blue"]
        measured = "Pax" if (hb or 0) >= HUE_PAX_MIN else ("Polly" if (hb or 0) <= HUE_POLLY_MAX else "?")
        if measured != j["char"]:
            bad.append(f"{rel(j['src'])}: named {j['char']}, body hue says {measured} "
                       f"(blue share {hb})")
    if bad:
        for b in bad:
            log(f"  !! {b}")
        sys.exit("refusing to run: character name and measured body colour disagree (A9)")
    log("  character check: every source's body hue matches its name")

    kept = []
    for j in jobs:
        plan_source(j)
        if j["first_gap"] is not None:
            log(f"  ~ gap    {rel(j['src'])}: real frames stop at #{j['first_gap']} "
                f"(decoded {j['src_frames']}) -> usable {j['usable']}, split {j['split']}")
        if j["label"] == "walking":
            if not j.get("tileable") and j["usable"] >= 2:
                log(f"  ✗ walking seam {j['seam_ratio']} > {LOOP_SEAM_MAX}: {rel(j['src'])}")
        if j["usable"] < 1:
            excluded.append({"source": rel(j["src"]), "md5": j["md5"],
                             "reason": f"no decodable frame before the first missing "
                                       f"timestamp (first gap #{j['first_gap']})"})
            continue
        if j["split"] == "start_only":
            why = (f"usable length {j['usable']} below the f{C.FLOOR} floor "
                   f"(first gap #{j['first_gap']}, decoded {j['src_frames']})")
            if j["base_angle"] in ("FRONT", C.HOLDOUT_ANGLE):
                why += "; kept as an eval start frame only"
            excluded.append({"source": rel(j["src"]), "md5": j["md5"], "reason": why})
        kept.append(j)
    jobs = kept

    # B11: the floor carries every trained label.
    f22_labels = {j["label"] for j in jobs if j["split"] == "train"}
    missing = [l for l in C.TRAINED_LABELS if l not in f22_labels]
    if missing:
        sys.exit(f"refusing to run: f{C.FLOOR} lacks trained labels {missing} (B11)")

    train_jobs = [j for j in jobs if j["split"] == "train"]
    assign_zooms(train_jobs)
    zp = verify_zoom_balance(train_jobs)
    if zp:
        for m in zp:
            log(f"  ! zoom imbalance {m}")
        sys.exit("refusing to run: zoom correlates with a factor (§5.4)")
    md5s = collections.Counter(j["md5"] for j in jobs)
    assert all(c == 1 for c in md5s.values()), "source md5 not unique"

    counts = count_table(jobs)
    log("\n§5.2 re-counted from raw (plan in parentheses):")
    diffs = print_table(counts)
    plan = Plan(jobs, toks)
    rung_n = collections.Counter(c["frames"] for c in plan.train)
    zoom_n = collections.Counter(c["zoom"] for c in plan.train)
    log(f"\ntraining clips: {len(plan.train)}  by bucket {dict(sorted(rung_n.items()))}  "
        f"by zoom {dict(sorted(zoom_n.items()))}")
    log(f"holdout {len(plan.holdout)} · calib {len(plan.calib)} · bank {len(plan.bank)} · "
        f"start frames {len(plan.starts)} · vae_gate {len(plan.vae)} + flat fill")
    log(f"captions: max {plan.max_tokens} tokens ({toks.method}), limit {C.MAX_CAPTION_TOKENS}")
    if diffs:
        log("\nDISAGREES WITH PLAN §5.2:")
        for d in diffs:
            log(f"  * {d}")
        if not args.accept_counts and not args.dry_run:
            sys.exit("refusing to run: counts disagree with PLAN §5.2 (fix the plan or pass "
                     "--accept-counts; deviations are then recorded in manifest.json)")

    if args.dry_run:
        items, missing_items = eval_items(plan, toks)
        log(f"eval items: {len(items)} ({sum(len(i['seeds']) for i in items)} clips); "
            f"missing start views: {missing_items}")
        log(f"dry run: nothing written ({time.time() - t0:.0f} s)")
        sys.exit(1 if diffs else 0)

    # ----------------------------------------------------------------------- build
    parts = set(args.only) if args.only else {"train", "holdout", "calib", "bank",
                                              "start_frames", "vae_gate"}
    parts.discard("json")
    if args.only:
        out = args.out
        if not out.is_dir():
            sys.exit(f"--only needs an existing corpus at {out}")
        for p in parts:
            for sub in {"train": ["clips", "png"], "holdout": ["holdout"], "calib": ["calib"],
                        "bank": ["bank"], "start_frames": ["start_frames"],
                        "vae_gate": ["vae_gate"]}[p]:
                shutil.rmtree(out / sub, ignore_errors=True)
        state = C.load_json(out / "build_state.json", {"dropped": []})
    else:
        if args.out.exists() and not args.force:
            sys.exit(f"{args.out} exists; pass --force to replace it (or --only PART)")
        out = args.out.with_name(args.out.name + ".partial")
        shutil.rmtree(out, ignore_errors=True)
        out.mkdir(parents=True)
        state = {"dropped": []}

    by_src = plan.by_source()
    work = [(j, by_src[id(j)]) for j in jobs if id(j) in by_src]
    done = [0]

    def run(item):
        j, items = item
        r = build_source(j, parts, out, items)
        with _print_lock:
            done[0] += 1
            if r["error"]:
                print(f"  ✗ dropped {rel(j['src'])}: {r['error']}", flush=True)
            elif done[0] % 20 == 0:
                print(f"  ... {done[0]}/{len(work)} sources ({time.time() - t0:.0f} s)", flush=True)
        return j, r

    log(f"\nbuilding {sorted(parts)} with {args.workers} workers ...")
    with ThreadPoolExecutor(args.workers) as ex:
        results = list(ex.map(run, work))
    if "vae_gate" in parts:
        write_flatfill(out)
    errors = [(j, r) for j, r in results if r["error"]]
    if errors:
        # A source that tears on all 24 decodes is dropped: re-plan without it so no file
        # or JSON references it, then fail loudly if that changes the §5.2 counts.
        state["dropped"] += [{"source": rel(j["src"]), "md5": j["md5"],
                              "reason": f"torn on all {DECODE_TRIES} decodes: {r['error']}"}
                             for j, r in errors]
        sys.exit(f"{len(errors)} source(s) failed to decode cleanly; re-run (tears are "
                 f"non-deterministic) or exclude them. Nothing was swapped into {args.out}.")
    C.write_json(out / "build_state.json", state)
    write_json_outputs(out, plan, jobs, excluded, counts, diffs, args, toks, state, rebased,
                       collisions)

    log("verifying outputs (frame counts, PNG counts, hashes, holdout disjointness) ...")
    probs = verify_outputs(out, plan, args.workers)
    if probs:
        for p in probs[:50]:
            log(f"  !! {p}")
        sys.exit(f"verification failed with {len(probs)} problem(s); corpus left at {out}")

    if not args.only:
        if args.out.exists():
            old = args.out.with_name(args.out.name + ".old")
            shutil.rmtree(old, ignore_errors=True)
            args.out.rename(old)
            out.rename(args.out)
            shutil.rmtree(old, ignore_errors=True)
        else:
            out.rename(args.out)
    size = sum(f.stat().st_size for f in args.out.rglob("*") if f.is_file())
    log(f"\nbuilt {args.out}: {len(plan.train)} training clips, {size / 1e9:.2f} GB, "
        f"{time.time() - t0:.0f} s")
    if diffs:
        log(f"NOTE: {len(diffs)} count deviation(s) from PLAN §5.2, recorded in manifest.json")


if __name__ == "__main__":
    main()
