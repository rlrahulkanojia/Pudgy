def frame_map(job, n):
    """Source frame index for each of the n output frames, and how it was made.

    'none'  : frames 0..n-1, all real, all before the first gap.
    'held'  : a 21-frame source -> 22: frames 0..20, then frame 20 once more (PLAN 5.1).
    'tiled' : walking -> frames 0..L-1 repeated (16 -> 0-15, 0-5) (PLAN 5.1, A11).
    None    : the source cannot supply n frames.
    """
    u = job["usable"]
    if u >= n:
        return list(range(n)), "none"
    if job["label"] == "walking" and job.get("tileable"):
        cyc = job["cycle_len"]
        return [i % cyc for i in range(n)], "tiled"
    if n == C.FLOOR and u == C.FLOOR - 1:
        return list(range(u)) + [u - 1], "held"
    return None, None


def check_map(job, n, m, how):
    """§5.6 'duplicates only where declared', asserted on the index map."""
    assert len(m) == n, (job["src"], n, len(m))
    if how == "none":
        assert m == list(range(n)) and n <= job["usable"]
    elif how == "held":
        assert job["usable"] == n - 1 and m == list(range(n - 1)) + [n - 2], (job["src"], m)
    elif how == "tiled":
        cyc = job["cycle_len"]
        assert job["label"] == "walking" and cyc <= job["usable"]
        assert m == [i % cyc for i in range(n)], (job["src"], m)
    else:
        raise AssertionError(how)


def bank_rung(job):
    """Longest legal rung the usable length reaches (held/tiled rules apply at 22)."""
    for n in sorted(C.BUCKETS, reverse=True):
        if frame_map(job, n)[0] is not None:
            return n
    return None


def plan_source(job):
    """Fill in split, training rungs and truncation for one preflighted source."""
    lab = job["label"]
    job["is_holdout"] = job["base_angle"] == C.HOLDOUT_ANGLE
    if lab == "walking":
        sr = job.get("seam_ratio")
        job["tileable"] = sr is not None and sr <= LOOP_SEAM_MAX and job["usable"] >= 2
        # v8 rule: a last frame that duplicates the first is dropped from the cycle.
        job["cycle_len"] = job["usable"] - 1 if (sr is not None and sr < LOOP_DUP_RATIO) \
            else job["usable"]
    f22_map, _ = frame_map(job, C.FLOOR)
    job["usable_f22"] = lab != "running" and f22_map is not None
    rungs = []
    if job["usable_f22"]:
        rungs.append(C.FLOOR)
        for n in (39, 56):
            if lab not in C.LONG_RUNG_LABELS[n] or job["usable"] < n:
                continue
            if n == 39 and lab != "neutral" and job["active"] < 39:
                continue                       # A5: the active length must reach 39
            rungs.append(n)
    job["rungs"] = rungs if not job["is_holdout"] else []
    if lab == "running":
        job["split"] = "untrained"
    elif not job["usable_f22"]:
        job["split"] = "start_only"
    else:
        job["split"] = "holdout" if job["is_holdout"] else "train"
    job["bank_frames"] = bank_rung(job) if job["usable_f22"] else (
        job["usable"] if lab == "running" and job["usable"] >= 2 else None)
    return job


def truncated(job, n):
    """v8's rule: a clip shorter than its source's usable length shows only the opening."""
    return n < job["usable"]


def assign_zooms(jobs):
    """Copied from finetune/wan/prep_v8.py assign_zooms at b902bde.

    One zoom per (source, ground), round-robin over a stable enumeration so the marginals
    are near-exact; verify_zoom_balance asserts it."""
    ladder = sorted(C.ZOOMS)
    for i, j in enumerate(sorted(jobs, key=lambda x: (x["kind"], x["char"], x["label"], x["angle"]))):
        j["zooms"] = {tag: ladder[(i + k) % len(ladder)] for k, tag in enumerate(C.TRAINED_GROUNDS)}
    return jobs


def verify_zoom_balance(jobs, tol=0.34):
    """Copied from finetune/wan/prep_v8.py verify_zoom_balance at b902bde (counted per
    training CLIP, i.e. per rung, so the f39/f56 rungs are balanced too)."""
    ladder = sorted(C.ZOOMS)
    even = 1.0 / len(ladder)
    factors = {"label": lambda j, g: j["label"], "character": lambda j, g: j["char"],
               "ground": lambda j, g: g, "angle": lambda j, g: j["base_angle"]}
    problems = []
    for fname, key in factors.items():
        tab = collections.defaultdict(collections.Counter)
        for j in jobs:
            for g in C.TRAINED_GROUNDS:
                tab[key(j, g)][j["zooms"][g]] += len(j["rungs"])
        for level, c in sorted(tab.items(), key=lambda kv: str(kv[0])):
            n = sum(c.values())
            for z in ladder:
                frac = c[z] / n
                if abs(frac - even) > tol:
                    problems.append(f"{fname}={level}: zoom {z} is {frac:.0%} of {n} "
                                    f"(want ~{even:.0%})")
    return problems


def count_table(jobs):
    """The §5.2 table, re-counted."""
    t = {lab: dict.fromkeys(COUNT_KEYS, 0) for lab in C.ALL_LABELS}
    for j in jobs:
        r = t[j["label"]]
        if j["usable_f22"]:
            r["usable_f22"] += 1
            if j["is_holdout"]:
                r["holdout"] += 1
            else:
                r["train_sources"] += 1
                r["f22_clips"] += len(C.TRAINED_GROUNDS)
                r["f39_sources"] += 39 in j["rungs"]
                r["f56_sources"] += 56 in j["rungs"]
    return t


def print_table(t):
    hdr = f"  {'label':<10}" + "".join(f"{k:>15}" for k in COUNT_KEYS)
    log(hdr)
    diffs = []
    tot = dict.fromkeys(COUNT_KEYS, 0)
    tot_e = [0] * len(COUNT_KEYS)
    for lab in C.ALL_LABELS:
        row = f"  {lab:<10}"
        for i, k in enumerate(COUNT_KEYS):
            got, want = t[lab][k], EXPECTED[lab][i]
            tot[k] += got
            tot_e[i] += want
            bad = got != want
            row += f"{got:>9} ({want:>3})"
            if bad:
                row += "*"
                diffs.append(f"{lab}.{k}: got {got}, plan {want}")
        log(row)
    log(f"  {'TOTAL':<10}" + "".join(f"{tot[k]:>9} ({tot_e[i]:>3})" for i, k in enumerate(COUNT_KEYS)))
    log("  (plan values in parentheses; * = disagrees with PLAN §5.2)")
    return diffs


