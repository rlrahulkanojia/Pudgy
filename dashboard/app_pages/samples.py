"""Samples: the v10 full-length remakes on their own, each with the prompt behind every part. No
comparisons. Written for the client, who took the remakes for copies of their videos, so the page
says plainly what is generated and what comes from the original skit (remake_v10.py's method)."""
import streamlit as st

import azure_utils

VIDEOS, PROMPTS = "v10/Full-length_remakes", "v10/prompts.json"   # both from upload_assets_v10.py


@st.cache_data(ttl=300, show_spinner=False)
def videos():
    return azure_utils.list_videos(VIDEOS)


@st.cache_data(ttl=300, show_spinner=False)
def prompts():
    return azure_utils.read_json(PROMPTS)


@st.cache_data(ttl=600, show_spinner=False)
def signed_url(blob):
    return azure_utils.signed_url(blob)


st.title("Samples")
st.markdown("Nine Pudgy Penguins skits made by the latest model (v10), each with the prompts that made it.")

with st.container(border=True):
    st.markdown("**These videos are generated by the model. They are not copies or edits of your videos.**")
    st.markdown(
        "- **The model has never seen these skits.** They were kept out of its training on purpose, so "
        "they show what it makes for material it has not learned from.\n"
        "- **What comes from the original skit:**\n"
        "  - **The prompts:** a written description of each part, shown next to each video.\n"
        "  - **Reference frames:** each video is made in parts of about 3 seconds at most. Each part starts "
        "and ends on a frame of the original, which sets the scene, where the characters stand and where the "
        "part ends up.\n"
        "  - **Timing and sound:** the video changes shot where the original does, so the original "
        "soundtrack fits.\n"
        "- **Everything in between is new.** Every frame between a part's start and end is generated by the "
        "model from the prompt, with its colours matched to the original."
    )

doc = (prompts() or {}).get("skits", {})
listed = videos()
if not listed:
    st.warning("The sample videos could not be loaded right now. Please try again in a few minutes.")

for blob, name in listed:
    title = name.rsplit(".", 1)[0].replace("_", " ")
    skit = doc.get(title)
    st.divider()
    st.subheader(title)
    left, right = st.columns([1, 2], gap="large")
    with left:
        st.video(signed_url(blob), width="stretch")
    with right:
        if not skit:
            st.caption("Prompts for this video are not available yet.")
            continue
        n = len(skit["shots"])
        st.caption(f"{skit['seconds']:.1f} s · {n} part{'s' * (n > 1)}")
        for i, s in enumerate(skit["shots"], 1):
            st.markdown(f"**Part {i}** · {s['start']:.1f}–{s['end']:.1f} s"
                        + (" · camera move, prompt written by hand" if s["manual"] else ""))
            st.code(s["prompt"], language=None, wrap_lines=True)
